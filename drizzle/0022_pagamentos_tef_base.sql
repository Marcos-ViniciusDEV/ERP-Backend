  `parcelas` int NOT NULL DEFAULT 1,
  `bandeira` varchar(50),
  `nsu` varchar(80),
  `codigoAutorizacao` varchar(80),
  `tid` varchar(120),
  `endToEndIdPix` varchar(120),
  `qrCodePix` text,
  `payloadOriginal` text,
  `erroCodigo` varchar(80),
