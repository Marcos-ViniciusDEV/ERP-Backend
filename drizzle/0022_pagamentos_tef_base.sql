  CONSTRAINT `transacoes_empresa_fk` FOREIGN KEY (`empresaId`) REFERENCES `empresas`(`id`),
  CONSTRAINT `transacoes_venda_fk` FOREIGN KEY (`vendaId`) REFERENCES `vendas`(`id`),
  CONSTRAINT `transacoes_terminal_fk` FOREIGN KEY (`terminalPagamentoId`) REFERENCES `terminais_pagamento`(`id`),
  CONSTRAINT `transacoes_forma_fk` FOREIGN KEY (`formaPagamentoEmpresaId`) REFERENCES `formas_pagamento_empresa`(`id`),
  CONSTRAINT `transacoes_provedor_fk` FOREIGN KEY (`provedorId`) REFERENCES `provedores_pagamento`(`id`),
  CONSTRAINT `transacoes_adquirente_fk` FOREIGN KEY (`adquirenteEmpresaId`) REFERENCES `adquirentes_empresa`(`id`)
);

