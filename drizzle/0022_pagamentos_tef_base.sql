CREATE TABLE IF NOT EXISTS `transacoes_pagamento` (
  `id` int AUTO_INCREMENT PRIMARY KEY,
  `empresaId` int NOT NULL,
  `vendaId` int,
  `vendaUuid` varchar(36),
  `pdvId` varchar(50),
  `terminalPagamentoId` int,
  `formaPagamentoEmpresaId` int,
  `provedorId` int,
  `adquirenteEmpresaId` int,
  `tipo` enum('dinheiro','debito','credito','pix','voucher','outro') NOT NULL,
  `modoCaptura` enum('manual','tef','pos_api','pix_integrado') NOT NULL DEFAULT 'manual',
